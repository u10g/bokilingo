/* ---------------------------------------------------------
   固定資産台帳ストーリー
   本試験の第2問（第7・12回）と同じ順で情報を出す：冒頭の指示 → 減価償却の条件（なお、…）→ 台帳の資産（取得の古い順）。
   資産を1つ読むごとに、その資産の期首減価償却累計額・当期減価償却費・期末帳簿価額を埋める。
   最後に、台帳のあとに問われる減価償却費と減価償却累計額（期末）の合計を求める。
   台帳の金額は domain/fixedAssets.ts で計算する（ここには空欄の行だけを書く）。数値・資産はオリジナル。
--------------------------------------------------------- */

