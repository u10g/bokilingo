  [
    `当社（決算年1回 3月31日）の当期（×${period}年4月1日〜×${period + 1}年3月31日）の固定資産台帳に、${kind}を1つずつ記入する。`,
    "なお、減価償却は残存価額ゼロの定額法により行い、期中に取得したものは月割で計算する。",
  ].join("\n");

