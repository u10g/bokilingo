/* ---------------------------------------------------------
   商品有高帳ストーリー
   本試験の第2問と同じ順で情報を出す：冒頭の指示 → 記入する欄の指示（なお、…）→ 日付順の取引。
   取引を1つ読むごとに、その取引で増える行（受入・払出・残高）の空欄を埋め、最後に売上総利益を求める。
   帳簿の金額は domain/inventory.ts で計算する（ここには空欄の位置だけを書く）。数値・場面はオリジナル。
--------------------------------------------------------- */

const intro = (method: InvMethod, item: string, txs: InvTx[]) =>
  [
    `次の${item}に関する取引にもとづいて、${method}によって商品有高帳に記入し、当月の売上高・売上原価・売上総利益を求める。`,
    ...returnNote(txs),
    txLine(txs[0]),
  ].join("\n");

const step = (tx: InvTx, cells: StoryInvCell[], distractors: string[], explanation: string): StoryStep => ({
  item: txLine(tx),
  entries: [],
  cells,
  distractors,
  explanation,
});

