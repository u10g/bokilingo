/* ---------------------------------------------------------
   勘定記入ストーリー
   本試験の第2問と同じ順で情報を出す：冒頭の指示 → 前提（前期末の処理・期首残高）→ 日付順の取引。
   取引を1つ読むごとに、その取引の摘要と金額を勘定に記入し、最後に締め切る。
   期首の再振替は受験者が行う処理なので、「期首を迎えた」ステップとして置く。
   勘定に関係しない取引（ひっかけ）も混ぜ、記入しないことを確かめる。
   会計期間は4月1日〜3月31日（売掛金は6月の1か月）。数値・場面はオリジナル。
   仕訳（entries）は勘定以外の科目も含めて書き、テストで貸借一致を検証する。
--------------------------------------------------------- */

